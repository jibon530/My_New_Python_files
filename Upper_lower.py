text = str(input("Enter the text\t:"))

t1 = text

print("Your Input\t:",text)

text = t1.lower()       #For lower case

print("Lowercase\t:",text)

text = t1.upper()       #For Upper case

print("Uppercase\t:",text)

text = t1.swapcase()    #FOr Swapcase

print("Swapcase\t:",text)

text = t1.title()       #For Title

print("Title\t\t:",text)